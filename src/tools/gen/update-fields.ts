/**
 * Writes `src/gen/UpdateFields.gen.ts` from AzerothCore `UpdateFields.h`: every field index, and the `Flags:`
 * visibility of each field as a set per object type (`PUBLIC` fields are the ones other players receive).
 * `bun src/tools/gen/update-fields.ts`
 */
const dir = new URL("../../../azerothcore/src/server/game/Entities/Object/Updates/", import.meta.url).pathname;
const text = await Bun.file(`${dir}UpdateFields.h`).text();
const values = new Map<string, number>();
const lines: string[] = ["/** Generated by `src/tools/gen/update-fields.ts` from AzerothCore `UpdateFields.h` (3.3.5a 12340). Do not edit. */", ""];
const flagsByField: { name: string; index: number; size: number; flags: string[] }[] = [];
for (const enumMatch of text.matchAll(/enum (\w+)\s*\{([\s\S]*?)\};/g)) {
  lines.push(`// ${enumMatch[1]}`);
  for (const line of enumMatch[2]!.split("\n")) {
    const m = /^\s*(\w+)\s*=\s*([^,]+),\s*(?:\/\/\s*Size:\s*(\d+),\s*Type:\s*\w+,\s*Flags:\s*(.*))?$/.exec(line);
    if (!m) continue;
    const expr = m[2]!.trim().replace(/\b([A-Z_][A-Z0-9_]*)\b/g, (name) => {
      if (!values.has(name)) throw new Error(`unknown ${name}`);
      return String(values.get(name));
    });
    const value = Function(`"use strict"; return (${expr});`)() as number;
    values.set(m[1]!, value);
    lines.push(`export const ${m[1]} = 0x${value.toString(16).padStart(4, "0")};`);
    if (m[3]) flagsByField.push({ name: m[1]!, index: value, size: Number(m[3]), flags: m[4]!.split(",").map((flag) => flag.trim()) });
  }
  lines.push("");
}
const publicOf = (prefixes: string[]): number[] => {
  const out: number[] = [];
  for (const field of flagsByField) {
    if (!prefixes.some((prefix) => field.name.startsWith(prefix)) || !field.flags.includes("PUBLIC")) continue;
    for (let i = 0; i < field.size; i++) out.push(field.index + i);
  }
  return out;
};
lines.push("/** Unit and player fields flagged `PUBLIC`: what every client that sees the player receives. */");
lines.push(`export const PLAYER_PUBLIC_FIELDS: ReadonlySet<number> = new Set([${publicOf(["OBJECT_", "UNIT_", "PLAYER_"]).join(", ")}]);`);
lines.push("");
await Bun.write(new URL("../../gen/UpdateFields.gen.ts", import.meta.url).pathname, lines.join("\n"));
