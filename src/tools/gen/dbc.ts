/**
 * Writes `src/gen/DBCStructure.gen.ts` from AzerothCore `DBCfmt.h`, `DBCStructure.h`, and `DBCStores.cpp`: for each
 * `DBCStorage<Entry> sXStore(fmt)` loaded with `LOAD_DBC`, the file, the `*_dbc` override table, the format, and the
 * struct member each stored column fills (arrays expanded as `name.0`, `name.1`, …).
 * `bun src/tools/gen/dbc.ts`
 */
const root = new URL("../../../azerothcore/src/server/", import.meta.url).pathname;
const fmtText = await Bun.file(`${root}shared/DataStores/DBCfmt.h`).text();
const structText = await Bun.file(`${root}shared/DataStores/DBCStructure.h`).text();
const enumsText = await Bun.file(`${root}shared/DataStores/DBCEnums.h`).text();
const storesText = await Bun.file(`${root}game/DataStores/DBCStores.cpp`).text();

const defines = new Map<string, number>();
for (const text of [structText, enumsText]) {
  for (const m of text.matchAll(/#define\s+(\w+)\s+(\d+)/g)) defines.set(m[1]!, Number(m[2]));
}
defines.set("TOTAL_LOCALES", 9);

const formats = new Map<string, string>();
for (const m of fmtText.matchAll(/char constexpr (\w+)\[\] = "([^"]*)"/g)) formats.set(m[1]!, m[2]!);

type Member = { name: string; type: "number" | "string"; count: number };

function structMembers(name: string): Member[] | null {
  const start = structText.search(new RegExp(`struct ${name}\\s*\\n\\{`));
  if (start < 0) return null;
  const body = structText.slice(structText.indexOf("{", start) + 1);
  const members: Member[] = [];
  let depth = 0;
  for (const raw of body.split("\n")) {
    const line = raw.replace(/\/\/.*$/, "").trim();
    if (depth === 0 && line.startsWith("};")) break;
    depth += (line.match(/\{/g) ?? []).length - (line.match(/\}/g) ?? []).length;
    if (depth !== 0 || !line || line.includes("(") || line.startsWith("[[") || line.startsWith("#")) continue;
    const m = /^(?:std::array<\s*)?(?:const\s+)?(uint32|int32|uint8|int8|uint16|int16|float|char const\*|char\s*const\s*\*|bool|uint64|DBCPosition3D)\s*(?:,\s*(\w+)\s*>)?\s+(\w+)(?:\[(\w+)\])?(?:\[(\w+)\])?\s*;/.exec(line);
    if (!m) continue;
    const size = (token: string | undefined): number => (token === undefined ? 1 : /^\d+$/.test(token) ? Number(token) : (defines.get(token) ?? NaN));
    const count = size(m[2]) * size(m[4]) * size(m[5]);
    if (Number.isNaN(count)) return null;
    if (m[1] === "DBCPosition3D") {
      for (const axis of ["X", "Y", "Z"]) members.push({ name: `${m[3]}.${axis}`, type: "number", count: 1 });
      continue;
    }
    members.push({ name: m[3]!, type: m[1]!.startsWith("char") ? "string" : "number", count });
  }
  return members;
}

type Store = { store: string; entry: string; fmtName: string; file: string; table: string };
const declared = new Map<string, { entry: string; fmtName: string }>();
for (const m of storesText.matchAll(/DBCStorage\s*<\s*(\w+)\s*>\s*(\w+)\((\w+)\);/g)) declared.set(m[2]!, { entry: m[1]!, fmtName: m[3]! });
const stores: Store[] = [];
for (const m of storesText.matchAll(/LOAD_DBC\((\w+),\s*"([^"]+)",\s*"([^"]+)"\)/g)) {
  const decl = declared.get(m[1]!);
  if (decl) stores.push({ store: m[1]!, entry: decl.entry, fmtName: decl.fmtName, file: m[2]!, table: m[3]! });
}

const out: string[] = [
  "/** Generated by `src/tools/gen/dbc.ts` from AzerothCore `DBCfmt.h`, `DBCStructure.h`, and `DBCStores.cpp`. Do not edit. */",
  "",
  "export type DBCStoreInfo = { file: string; table: string; fmt: string; fields: readonly string[] };",
  "",
];
const skipped: string[] = [];
for (const store of stores) {
  const fmt = formats.get(store.fmtName);
  const members = structMembers(store.entry);
  if (!fmt || !members) {
    skipped.push(`${store.store} (no ${fmt ? "struct" : "format"})`);
    continue;
  }
  const flat: { name: string; type: string }[] = [];
  for (const member of members) {
    for (let i = 0; i < member.count; i++) flat.push({ name: member.count > 1 ? `${member.name}.${i}` : member.name, type: member.type });
  }
  const stored = [...fmt].filter((c) => c !== "x" && c !== "X" && c !== "d").length;
  if (stored !== flat.length) {
    skipped.push(`${store.store} (${stored} stored columns, ${flat.length} members)`);
    continue;
  }
  const fields: string[] = [];
  let next = 0;
  for (const c of fmt) {
    if (c === "x" || c === "X" || c === "d") fields.push("");
    else fields.push(flat[next++]!.name);
  }
  const tsFields = members.map((member) => {
    const base = member.name.includes(".") ? null : member.type;
    if (!base) return null;
    return `  ${member.name}: ${member.count > 1 ? `${base}[]` : base};`;
  });
  const nested = new Map<string, string[]>();
  for (const member of members) {
    if (!member.name.includes(".")) continue;
    const [head, axis] = member.name.split(".");
    nested.set(head!, [...(nested.get(head!) ?? []), axis!]);
  }
  out.push(`export type ${store.entry} = {`);
  out.push(...tsFields.filter((line): line is string => line !== null));
  for (const [head, axes] of nested) out.push(`  ${head}: { ${axes.map((axis) => `${axis}: number`).join("; ")} };`);
  out.push("};");
  out.push(`export const ${store.store}Info: DBCStoreInfo = ${JSON.stringify({ file: store.file, table: store.table, fmt, fields })};`);
  out.push("");
}
await Bun.write(new URL("../../gen/DBCStructure.gen.ts", import.meta.url).pathname, out.join("\n"));

const generated = stores.filter((store) => !skipped.some((line) => line.startsWith(`${store.store} `)));
const storesOut = [
  "/** Generated by `src/tools/gen/dbc.ts`: every `DBCStorage` `DBCStores.cpp` loads with `LOAD_DBC`. Do not edit. */",
  "",
  'import { DBCStorage } from "../shared/DataStores/DBCStore.ts";',
  `import type { ${[...new Set(generated.map((store) => store.entry))].join(", ")} } from "./DBCStructure.gen.ts";`,
  `import { ${generated.map((store) => `${store.store}Info`).join(", ")} } from "./DBCStructure.gen.ts";`,
  "",
  ...generated.map((store) => `export const ${store.store} = new DBCStorage<${store.entry}>(${store.store}Info);`),
  "",
  `export const ALL_DBC_STORES: readonly DBCStorage<object>[] = [${generated.map((store) => store.store).join(", ")}];`,
  "",
];
await Bun.write(new URL("../../gen/DBCStores.gen.ts", import.meta.url).pathname, storesOut.join("\n"));
if (skipped.length) console.log(`skipped: ${skipped.join(", ")}`);
