/**
 * Writes `src/gen/{Login,Character,World}Database.gen.ts` from AzerothCore's `*Database.cpp`: every
 * `PrepareStatement(NAME, "sql", CONNECTION_*)` under its C++ name, with the SQL text unchanged.
 * `bun src/tools/gen/statements.ts`
 */
const dir = new URL("../../../azerothcore/src/server/database/Database/Implementation/", import.meta.url).pathname;
const out = new URL("../../gen/", import.meta.url).pathname;

for (const name of ["Login", "Character", "World"]) {
  const text = await Bun.file(`${dir}${name}Database.cpp`).text();
  const re = /PrepareStatement\(\s*(\w+)\s*,\s*((?:"(?:[^"\\]|\\.)*"\s*)+),\s*(CONNECTION_\w+)\s*\)/g;
  const lines = [
    `/** Generated by \`src/tools/gen/statements.ts\` from AzerothCore \`${name}Database.cpp\`. Do not edit. */`,
    "",
  ];
  let count = 0;
  for (const match of text.matchAll(re)) {
    const sql = [...match[2]!.matchAll(/"((?:[^"\\]|\\.)*)"/g)].map((part) => JSON.parse(`"${part[1]}"`) as string).join("");
    lines.push(`/** ${match[3]} */`);
    lines.push(`export const ${match[1]} = ${JSON.stringify(sql)};`);
    count++;
  }
  const expected = (text.match(/PrepareStatement\(/g) ?? []).length;
  if (count !== expected) throw new Error(`${name}Database.cpp: parsed ${count} of ${expected} statements`);
  await Bun.write(`${out}${name}Database.gen.ts`, `${lines.join("\n")}\n`);
}
